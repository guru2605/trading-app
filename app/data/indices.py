def get_all_unique_symbols() -> list[tuple[str, str]]:
    """Deduplicated list of all (tradingsymbol, exchange) pairs across every index."""
    seen: set[tuple[str, str]] = set()
    result: list[tuple[str, str]] = []
    for index_list in ALL_INDEX_LISTS:
        for sym, exch in index_list:
            key = (sym, exch)
            if key not in seen:
                seen.add(key)
                result.append(key)
    return result
